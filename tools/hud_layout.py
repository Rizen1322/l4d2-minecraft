"""Shared compact native HUD layout, in Source's 480-height virtual pixels."""
X = 5
BOTTOM = 205
STRIDE = 49
WIDTH = 112
TOP_INSET = 2
HEIGHT = 60


def covered(x, y, width, height, count, gui=False):
    if gui or height <= 0 or width <= 0:
        return False
    vx, vy = x * 480 / height, y * 480 / height
    for slot in range(max(0, min(3, count))):
        top = 480 - BOTTOM + (3 - slot) * STRIDE + TOP_INSET
        if X - 2 <= vx < X + WIDTH and top <= vy < top + HEIGHT:
            return True
    return False


def shader_header():
    return f'''// Generated by tools/build_hud.py from hud_layout.py. Native panel footprints only.
uniform int TeammateHudCount = 0;
bool nativeTeamHud(float2 pixel)
{{
    const float2 p = pixel * (480.0 / BUFFER_HEIGHT);
    if (p.x < {X-2}.0 || p.x >= {X+WIDTH}.0) return false;
    [unroll] for (int slot = 0; slot < 3; ++slot)
    {{
        const float top = {480-BOTTOM+3*STRIDE+TOP_INSET}.0 - slot * {STRIDE}.0;
        if (slot < TeammateHudCount && p.y >= top && p.y < top + {HEIGHT}.0) return true;
    }}
    return false;
}}
'''
